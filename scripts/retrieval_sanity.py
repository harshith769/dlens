"""Retrieval sanity metric (S07, retrieval-design.md §9). REPORT ONLY, NOT A GATE, not the
benchmark metric (eval/metrics.py is the owner's).

For each dev question in eval/questions/dev.jsonl, the query is the question text verbatim. A hit
is the column card whose name equals the question's gold ``target`` (from the question file,
never from parser output). Questions whose target has no card (dev-19: the column doesn't exist)
are excluded. Reports recall@5 and @10 for bm25, dense and hybrid on synthetic_shop, plus index
size and build time (synthetic_shop, and dbt_jira if ``--jira-target`` is given).

    uv run --extra retrieval python scripts/retrieval_sanity.py \\
        [--jira-target PATH/integration_tests/target] [--out eval/reports/retrieval-sanity.md]

Needs the retrieval extra and the pinned model (downloaded once into the HF cache).
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any

from dlens.graph import LineageGraph, load_or_build
from dlens.graph.cache import cache_path, load_artifact_cache
from dlens.retrieval.dense import OnnxEmbedder
from dlens.retrieval.index import SearchIndex, artifact_index_dir, project_index_dir

ROOT = Path(__file__).resolve().parents[1]
DEV = ROOT / "eval" / "questions" / "dev.jsonl"
SS = ROOT / "corpora" / "synthetic_shop"
MODES = ("bm25", "dense", "hybrid")
KS = (5, 10)


def _build(
    graph: LineageGraph,
    graph_file: Path,
    target: Path,
    project: Path | None,
    index_dir: Path,
    emb: OnnxEmbedder,
) -> tuple[SearchIndex, float, int]:
    t0 = time.perf_counter()
    idx, _ = SearchIndex.open(
        graph=graph,
        graph_file=graph_file,
        target_dir=target,
        project_dir=project,
        index_dir=index_dir,
        embedder=emb,
        rebuild=True,
    )
    took = time.perf_counter() - t0
    size = sum(p.stat().st_size for p in index_dir.iterdir() if p.is_file())
    return idx, took, size


def _rank(idx: SearchIndex, query: str, target: str, mode: str) -> int | None:
    title = f"{target} · column"
    for h in idx.search(query, k=max(KS), mode=mode):  # type: ignore[arg-type]
        if h.chunk.kind == "column" and h.chunk.title.split(" (part")[0] == title:
            return h.rank
    return None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jira-target", type=Path)
    ap.add_argument("--out", type=Path, default=ROOT / "eval" / "reports" / "retrieval-sanity.md")
    args = ap.parse_args()

    emb = OnnxEmbedder()
    graph = load_or_build(SS)
    ss_idx, ss_s, ss_bytes = _build(
        graph, cache_path(SS), SS / "target", SS, project_index_dir(SS), emb
    )
    cards = {c.title.split(" (part")[0] for c in ss_idx.chunks if c.kind == "column"}

    rows: list[dict[str, Any]] = []
    excluded: list[str] = []
    for line in DEV.read_text(encoding="utf-8").splitlines():
        q = json.loads(line)
        if f"{q['target']} · column" not in cards:
            excluded.append(f"{q['id']} ({q['target']}: no card)")
            continue
        ranks = {m: _rank(ss_idx, q["question"], q["target"], m) for m in MODES}
        rows.append({"id": q["id"], "wording": q["wording"], "target": q["target"], **ranks})

    def recall(mode: str, k: int, subset: list[dict[str, Any]]) -> str:
        if not subset:
            return "–"
        hit = sum(1 for r in subset if r[mode] is not None and r[mode] <= k)
        return f"{hit}/{len(subset)} = {hit / len(subset):.2f}"

    st = ss_idx.meta["stats"]
    out = [
        "# Retrieval sanity check (S07)",
        "",
        "Report only; not a gate and not the benchmark metric. Generated by",
        "`scripts/retrieval_sanity.py` with the real model "
        f"(`{emb.model}`, {emb.name}, {emb.threads} threads).",
        "",
        "Query is the dev question text verbatim; a hit is the column card named by the "
        "question's gold `target`.",
        f"n = {len(rows)}. Excluded: {', '.join(excluded) or 'none'}.",
        "",
        "## Recall of the gold target's card (synthetic_shop)",
        "",
        "| mode | recall@5 | recall@10 | identifier-worded @5 | description-worded @5 |",
        "|---|---|---|---|---|",
    ]
    ident = [r for r in rows if r["wording"] == "identifier"]
    desc = [r for r in rows if r["wording"] != "identifier"]
    for m in MODES:
        out.append(
            f"| {m} | {recall(m, 5, rows)} | {recall(m, 10, rows)} | "
            f"{recall(m, 5, ident)} | {recall(m, 5, desc)} |"
        )
    out += [
        "",
        f"{len(ident)} of {len(rows)} questions name the target identifier verbatim, which "
        "favours BM25; the description-worded rows are the paraphrase case dense retrieval is "
        "for (too few to conclude anything).",
        "",
        "Per question (rank of the gold card in the top 10, – if absent):",
        "",
        "| id | wording | target | bm25 | dense | hybrid |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        cells = [str(r[m]) if r[m] is not None else "–" for m in MODES]
        out.append(f"| {r['id']} | {r['wording']} | `{r['target']}` | " + " | ".join(cells) + " |")

    def index_row(name: str, idx: SearchIndex, secs: float, size: int) -> str:
        s = idx.meta["stats"]
        lb = s["line_basis"]
        return (
            f"| {name} | {s['chunks']} ({s['chunks_model']} model, {s['chunks_column']} column, "
            f"{s['chunks_doc']} doc) | {lb['source']} / {lb['compiled']} | "
            f"{s['wordpieces_max']} / {s['wordpieces_p95']} | {s['wordpieces_over_max']} | "
            f"{size / 1e6:.2f} MB | {secs:.1f} s |"
        )

    out += [
        "",
        "## Index size and build time",
        "",
        "| corpus | chunks | line basis source / compiled | wordpieces max / p95 | over 512 "
        "| index size | build time |",
        "|---|---|---|---|---|---|---|",
        index_row("synthetic_shop", ss_idx, ss_s, ss_bytes),
    ]
    parser_only = [
        ("synthetic_shop", st),
    ]
    if args.jira_target is not None:
        jt = args.jira_target
        jg = load_artifact_cache(jt)
        cache = jt / "dlens"
        proj = jt.parent if (jt.parent / "dbt_project.yml").is_file() else None
        j_idx, j_s, j_bytes = _build(
            jg, cache / "graph.json", jt, proj, artifact_index_dir(cache), emb
        )
        out.append(index_row("dbt_jira", j_idx, j_s, j_bytes))
        parser_only.append(("dbt_jira", j_idx.meta["stats"]))
    out += [
        "",
        "Build time includes chunking, the tokenizer gate and embedding (4 threads, CPU); the "
        "model load is excluded.",
        "",
        "Columns without a card (parser-only: neither YAML-declared nor in catalog.json):",
        "",
        "| corpus | ephemeral | catalog-less schema growth | not in catalog |",
        "|---|---|---|---|",
    ]
    for name, s in parser_only:
        out.append(
            f"| {name} | {s['parser_only_ephemeral']} | {s['parser_only_schema_growth']} | "
            f"{s['parser_only_not_in_catalog']} |"
        )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
