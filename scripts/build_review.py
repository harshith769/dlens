"""Build the owner's review files for the dev questions (S09, questions-design.md §8).

uv run python scripts/build_review.py

Reads eval/questions/review/dev_candidates.jsonl and the paraphrase picks (paraphrases.jsonl) and
writes:
- eval/questions/review/dev_review.md: one row per question, flagged rows first, then the spares;
- eval/questions/review/dev_decisions.yml: `decision: pending` for every question. Decisions the
  owner already set are kept; only missing ids are added.
Nothing here changes a question's gold. A paraphrase pick replaces the question text, and the
template stays in `template_question`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).parents[1]
REVIEW = ROOT / "eval" / "questions" / "review"
CANDIDATES = REVIEW / "dev_candidates.jsonl"
PARAPHRASES = REVIEW / "paraphrases.jsonl"
OUT_MD = REVIEW / "dev_review.md"
DECISIONS = REVIEW / "dev_decisions.yml"
LARGE_GOLD = 40  # impact answers above this many columns are flagged (3K-token answer budget)


def merged() -> list[dict[str, Any]]:
    """Candidates with the paraphrase picks applied (stale picks ignored)."""
    picks = {}
    if PARAPHRASES.is_file():
        picks = {r["id"]: r for r in map(json.loads, PARAPHRASES.read_text().splitlines())}
    out = []
    for q in map(json.loads, CANDIDATES.read_text().splitlines()):
        q = dict(q, review_flags=list(q["review_flags"]))
        if "paraphrase_pending" in q["review_flags"]:
            q["review_flags"].remove("paraphrase_pending")
            r = picks.get(q["id"])
            if r is None or r["template"] != q["template_question"]:
                q["review_flags"].append("paraphrase_missing")
            elif r["pick"] is None:
                q["review_flags"].append("no_clean_paraphrase: template kept")
            else:
                q["question"] = r["pick"]
                q["review_flags"].append(f"paraphrased ({r['pick_style']})")
                bad = [c for c in r["candidates"] if c["flags"]]
                if bad:
                    q["review_flags"].append(f"paraphrase_candidates_flagged: {len(bad)} of 3")
        n = len((q["gold"].get("downstream") or {}).get("all", []))
        if q["type"] == "impact" and n > LARGE_GOLD:
            q["review_flags"].append(f"large_gold: {n} downstream columns")
        out.append(q)
    return out


def short(items: list[str], n: int = 4) -> str:
    more = f" +{len(items) - n}" if len(items) > n else ""
    return ", ".join(items[:n]) + more


def gold_summary(q: dict[str, Any]) -> str:
    g, st = q["gold"], q["subtype"]
    if q["type"] == "unanswerable":
        return f"refused; closest: {short(g.get('closest', []))}"
    if q["type"] == "ask":
        return " / ".join(f["fact"] for f in g["facts"])
    if st == "yesno":
        r = g["reach"]
        return f"direct: {r['direct']}, all: {r['all']}; path: {' → '.join(r['path']) or '-'}"
    if st == "downstream":
        d, m, e = g["downstream"], g["models"], g["exposures"]
        focus = " (asks for dashboards)" if g.get("focus") == "exposures" else ""
        return (
            f"downstream {len(d['direct'])} direct / {len(d['all'])} all; models "
            f"{len(m['direct'])} / {len(m['all'])}; exposures {short(e['all']) or '-'}{focus}"
        )
    inputs = g["inputs"]
    ind = [f"{x['from']} ({x['type']})" for x in inputs["indirect"]]
    base = f"inputs: {short(inputs['direct'])}" + (f"; indirect: {short(ind, 3)}" if ind else "")
    if st == "false_premise":
        p = g["premise"]
        return (
            f"premise {p['edge']['from']} → {p['edge']['to']}: direct edge "
            f"{'yes' if p['direct_edge'] else 'no'}, upstream at all "
            f"{'yes' if p['reaches_all'] else 'no'}; {base}"
        )
    if st == "computed":
        return base
    up = g["upstream"]
    text = (
        f"{base}; upstream {len(up['direct'])} / {len(up['all'])}; sources {short(g['sources'], 3)}"
    )
    if st == "ambiguous":
        text = f"{g['verdict']}; candidates: {', '.join(g['candidates'])}; " + text
    if st == "multi_part":
        text += f"; out of scope: {g['out_of_scope']}"
    return text


def cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(questions: list[dict[str, Any]]) -> str:
    main = [q for q in questions if not q.get("spare")]
    spares = [q for q in questions if q.get("spare")]
    flagged = [q for q in main if q["review_flags"]]
    clean = [q for q in main if not q["review_flags"]]
    head = [
        "# Dev questions: owner review (S09)",
        "",
        "GENERATED by scripts/build_review.py from dev_candidates.jsonl and paraphrases.jsonl.",
        "Set a decision for every id in dev_decisions.yml: `accept`, `fix` (with `text:`), or `drop`",
        "(with `replacement:` a spare of the same row). `make check-review` must pass before",
        "scripts/apply_review.py writes eval/questions/dev.jsonl. Full gold: dev_candidates.jsonl.",
        "",
        f"{len(main)} questions ({len(flagged)} flagged, listed first) + {len(spares)} spares.",
        "",
    ]
    cols = "| id | type / subtype | strata (hop · traps · wording) | question | target | gold | flags |"
    sep = "|---|---|---|---|---|---|---|"

    def rows(qs: list[dict[str, Any]]) -> list[str]:
        out = []
        for q in qs:
            strata = f"{q['hop_bucket'] or '-'} · {', '.join(q['traps']) or '-'} · {q['wording']}"
            text = q["question"]
            if q.get("template_question") and q["template_question"] != text:
                text += f" (template: {q['template_question']})"
            out.append(
                f"| {q['id']} | {q['type']} / {q['subtype']} | {cell(strata)} | {cell(text)} | "
                f"{cell(q['target'])} | {cell(gold_summary(q))} | {cell('; '.join(q['review_flags']))} |"
            )
        return out

    body = ["## Flagged", "", cols, sep, *rows(flagged), "", "## Not flagged", "", cols, sep,
            *rows(clean), "", "## Spares (used only to replace a dropped question)", "", cols, sep,
            *rows(spares)]  # fmt: skip
    return "\n".join(head + body) + "\n"


def decisions(questions: list[dict[str, Any]]) -> dict[str, Any]:
    old: dict[str, Any] = {}
    if DECISIONS.is_file():
        old = (yaml.safe_load(DECISIONS.read_text()) or {}).get("decisions") or {}
    out = {}
    for q in questions:
        out[q["id"]] = old.get(q["id"]) or {
            "decision": "pending" if not q.get("spare") else "unused"
        }
    return {"decisions": out}


def render_decisions(d: dict[str, Any]) -> str:
    head = (
        "# Owner decisions for the dev questions (S09). One entry per question id.\n"
        "# decision: accept | fix (add text: new question text) | drop (add replacement: dev-sNN)\n"
        "# Spares stay `unused` unless they replace a dropped question (then accept or fix).\n"
        "# Optional per entry: note, wording, source (re-labels). `make check-review` enforces the\n"
        "# rules.\n"
    )
    lines = [head, "decisions:"]
    for qid, entry in d["decisions"].items():
        lines.append(
            f"  {qid}: " + yaml.safe_dump(entry, default_flow_style=True, width=1000).strip()
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    questions = merged()
    OUT_MD.write_text(render(questions))
    DECISIONS.write_text(render_decisions(decisions(questions)))
    print(f"wrote {OUT_MD.relative_to(ROOT)} and {DECISIONS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
